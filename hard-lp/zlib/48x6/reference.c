unsigned benchmark_entry(void) {
    int len, best_len = 2;
    unsigned match_start = 0;
    Byte scan_end1 = input[best_len - 1];
    Byte scan_end = input[best_len];

    for (unsigned i = 0; i < 48; ++i) {
    if (candidate[i][best_len] != scan_end ||
        candidate[i][best_len - 1] != scan_end1 ||
        candidate[i][0] != input[0] ||
        candidate[i][1] != input[1])
        continue;
    if (candidate[i][3] != input[3]) {
        len = 3;
        goto checked;
    }
    if (candidate[i][4] != input[4]) {
        len = 4;
        goto checked;
    }
    if (candidate[i][5] != input[5]) {
        len = 5;
        goto checked;
    }
    if (candidate[i][6] != input[6]) {
        len = 6;
        goto checked;
    }
    if (candidate[i][7] != input[7]) {
        len = 7;
        goto checked;
    }
    if (candidate[i][8] != input[8]) {
        len = 8;
        goto checked;
    }
    len = 9;
checked:
    if (len > best_len) {
        match_start = (48 - i) * 32;
        best_len = len;
        if (len >= 9)
            goto finish;
        scan_end1 = input[best_len - 1];
        scan_end = input[best_len];
    }

    }
finish:
    return (match_start << 8) | (best_len <= 10 ? best_len : 10);
}
